package com.tecnm.merida.library_backend.web.controller;

import com.tecnm.merida.library_backend.domain.Genre;
import com.tecnm.merida.library_backend.domain.service.GenreService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.ExampleObject;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.responses.ApiResponses;
import io.swagger.v3.oas.annotations.security.SecurityRequirement;
import io.swagger.v3.oas.annotations.tags.Tag;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.util.List;

@RestController
@RequestMapping("/genres")
@Tag(name = "Genre", description = "Catalog of book genres")
@SecurityRequirement(name = "bearerAuth")
public class GenreController {

    private final GenreService genreService;

    @Autowired
    public GenreController(GenreService genreService) {
        this.genreService = genreService;
    }

    @GetMapping("")
    @Operation(summary = "Get all genres", description = "Returns the list of all genres")
    @ApiResponses({
            @ApiResponse(responseCode = "200", description = "Genres retrieved successfully"),
            @ApiResponse(responseCode = "401", description = "Unauthorized: missing or invalid token"),
            @ApiResponse(responseCode = "403", description = "Forbidden: access denied")
    })
    public ResponseEntity<List<Genre>> getAll() {
        return new ResponseEntity<>(genreService.getAll(), HttpStatus.OK);
    }

    @GetMapping("/{id}")
    @Operation(summary = "Get genre by ID", description = "Returns one genre by its ID")
    @ApiResponses({
            @ApiResponse(responseCode = "200", description = "Genre found"),
            @ApiResponse(responseCode = "400", description = "Invalid ID format"),
            @ApiResponse(responseCode = "401", description = "Unauthorized: missing or invalid token"),
            @ApiResponse(responseCode = "403", description = "Forbidden: access denied"),
            @ApiResponse(responseCode = "404", description = "Genre not found")
    })
    public ResponseEntity<Genre> getGenre(
            @Parameter(description = "ID of the genre", example = "1", required = true)
            @PathVariable("id") int genreId) {
        return genreService.getGenre(genreId)
                .map(ResponseEntity::ok)
                .orElse(ResponseEntity.notFound().build());
    }

    @PostMapping("")
    @Operation(
            summary = "Create a genre",
            description = "Registers a new genre. The ID is generated by the database",
            requestBody = @io.swagger.v3.oas.annotations.parameters.RequestBody(
                    required = true,
                    content = @Content(
                            mediaType = "application/json",
                            examples = @ExampleObject(
                                    name = "New genre",
                                    value = """
                                            {
                                              "name": "Poesia",
                                              "active": true
                                            }
                                            """
                            )
                    )
            )
    )
    @ApiResponses({
            @ApiResponse(responseCode = "201", description = "Genre created successfully"),
            @ApiResponse(responseCode = "400", description = "Invalid data"),
            @ApiResponse(responseCode = "401", description = "Unauthorized: missing or invalid token"),
            @ApiResponse(responseCode = "403", description = "Forbidden: access denied")
    })
    public ResponseEntity<Genre> save(@RequestBody Genre genre) {
        return new ResponseEntity<>(genreService.save(genre), HttpStatus.CREATED);
    }

    @PutMapping("/{id}")
    @Operation(
            summary = "Update a genre",
            description = "Updates the data of an existing genre",
            requestBody = @io.swagger.v3.oas.annotations.parameters.RequestBody(
                    required = true,
                    content = @Content(
                            mediaType = "application/json",
                            examples = @ExampleObject(
                                    name = "Update genre",
                                    value = """
                                            {
                                              "name": "Poesia latinoamericana",
                                              "active": false
                                            }
                                            """
                            )
                    )
            )
    )
    @ApiResponses({
            @ApiResponse(responseCode = "200", description = "Genre updated successfully"),
            @ApiResponse(responseCode = "400", description = "Invalid data"),
            @ApiResponse(responseCode = "401", description = "Unauthorized: missing or invalid token"),
            @ApiResponse(responseCode = "403", description = "Forbidden: access denied"),
            @ApiResponse(responseCode = "404", description = "Genre not found")
    })
    public ResponseEntity<Genre> update(
            @Parameter(description = "ID of the genre to update", example = "6", required = true)
            @PathVariable("id") int genreId,
            @RequestBody Genre genre) {
        return genreService.update(genreId, genre)
                .map(ResponseEntity::ok)
                .orElse(ResponseEntity.notFound().build());
    }

    @DeleteMapping("/{id}")
    @Operation(summary = "Delete a genre", description = "Deletes a genre if it exists and has no books")
    @ApiResponses({
            @ApiResponse(responseCode = "200", description = "Genre deleted successfully"),
            @ApiResponse(responseCode = "400", description = "Invalid ID format"),
            @ApiResponse(responseCode = "401", description = "Unauthorized: missing or invalid token"),
            @ApiResponse(responseCode = "403", description = "Forbidden: access denied"),
            @ApiResponse(responseCode = "404", description = "Genre not found"),
            @ApiResponse(responseCode = "409", description = "The genre has books and cannot be deleted")
    })
    public ResponseEntity<Void> delete(
            @Parameter(description = "ID of the genre to delete", example = "6", required = true)
            @PathVariable("id") int genreId) {
        if (genreService.delete(genreId)) {
            return ResponseEntity.ok().build();
        }
        return ResponseEntity.notFound().build();
    }
}